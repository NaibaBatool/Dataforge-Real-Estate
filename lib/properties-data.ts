export function getPropertyById(id: string): Property | undefined {
  return PROPERTIES_DATA.find((p) => p.id === id)
}

export function getAllProperties(): Property[] {
  return PROPERTIES_DATA
}

export function filterProperties(params: {
  purpose?: string
  type?: string
  area?: string
  minPrice?: number
  maxPrice?: number
  featured?: boolean
}): Property[] {
  return PROPERTIES_DATA.filter((p) => {
    if (params.purpose && params.purpose !== "all" && p.purpose !== params.purpose) {
      return false
    }
    if (params.type && params.type !== "all" && p.type !== params.type) {
      return false
    }
    if (params.area && params.area !== "all" && p.area.toLowerCase() !== params.area.toLowerCase()) {
      return false
    }
    if (params.minPrice !== undefined && p.price < params.minPrice) {
      return false
    }
    if (params.maxPrice !== undefined && p.price > params.maxPrice) {
      return false
    }
    if (params.featured && !p.featured) {
      return false
    }
    return true
  })
}
